// Pins T18 of the doc-comments build (docs/active/specs/2026-09-26-doc-
// comments-build-design.md §4.3a, §8): reading Excel legacy cell Notes off a
// REAL .xlsx, in Kotlin, with java.util.zip + javax.xml.parsers — no Android
// framework classes, no instrumented/on-device test (a plain `./gradlew
// test` JVM unit test, per T18's own pinning-test row).
//
// Fixture: app/src/test/resources/doc-comments/q3-sales-by-rep.xlsx — the
// SAME file desktop/tests/xlsx-comments.test.ts (T12) reads, copied verbatim
// from desktop/tests/fixtures/doc-comments/, so a fixture drift here can
// never silently make the cross-platform parity claim compare two different
// inputs (the exact risk T18's own design row warns about — the same
// reasoning T16's own docx test documents for its fixtures).
//
// Golden parity: app/src/test/resources/doc-comments/golden/
// q3-sales-by-rep.json is the REAL desktop `readXlsxComments` reader's own
// output, generated by desktop/tests/fixtures/doc-comments/
// generate-xlsx-golden.mjs (committed alongside this test). **`createdAt` is
// EXCLUDED from the comparison, top-level and within every reply** — unlike
// docx's `w:date`-derived (deterministic) timestamp, a legacy Excel Note
// carries NO timestamp of its own (§4.1), so both readers stamp a fresh
// wall-clock value at READ time (`Date.now()` on desktop, `System.
// currentTimeMillis()` here) — comparing it byte-for-byte across two
// separate processes run at two different moments would be asserting on
// wall-clock time, exactly what `.claude/rules/test-suite-hygiene.md` (§
// "Never assert on wall-clock time") forbids. Every OTHER field is compared
// exactly, field for field.
