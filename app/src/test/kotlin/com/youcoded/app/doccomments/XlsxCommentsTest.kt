    @Test
    fun notAValidZipRefusesHonestlyInsteadOfThrowing() {
        val garbage = Files.createTempFile("ycd-xlsx-read-", "-garbage.xlsx").toFile()
        garbage.deleteOnExit()
        garbage.writeBytes("not a workbook".toByteArray(Charsets.UTF_8))
