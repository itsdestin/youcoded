    }

    // ── resolve-b19-sibling: resolve ONE of elden's real 5 independent
    // threads on B19 — the other four (and every other thread in the whole
    // ~700-thread workbook) must be completely untouched. ──
    @Test
    fun resolveB19Sibling() {
        val json = JSONObject(String(xlsxParityResourceBytes("write-golden/resolve-b19-sibling.json"), Charsets.UTF_8))
        val fixture = json.getString("fixture")
        val path = json.getString("path")
        val step = json.getJSONArray("steps").getJSONObject(0)
        val args = step.getJSONObject("args")
        val targetId = args.getString("id")

        val originalBytes = xlsxParityResourceBytes(fixture)
        val kotlinTarget = xlsxParityScratchCopy(originalBytes, fixture)
        val home = xlsxParityScratchHome()

        val before = xlsxParityReadOk(kotlinTarget, path)
        val b19Before = before.filter { c -> val s = c.selector; s is CommentSelector.Cell && s.selector.cell == "B19" }
        assertEquals(5, b19Before.size, "elden's real B19 cell carries 5 independent threads")

        val result = runBlocking { resolveXlsxComment(kotlinTarget.absolutePath, path, targetId, home) }
        assertTrue(result is XlsxWriteResult.Ok, "Kotlin resolve failed: $result")

        val desktopGolden = xlsxParityScratchCopy(xlsxParityResourceBytes("write-golden/resolve-b19-sibling.xlsx"), "desktop-resolve-b19-sibling.xlsx")
        val desktopComments = xlsxParityReadOk(desktopGolden, path)
        val kotlinComments = xlsxParityReadOk(kotlinTarget, path)

        // Same pre-existing GUID both sides (never re-minted by resolve) —
        // exact id equality is meaningful here, unlike the `add`-originated
        // cases above.
        val desktopTarget = desktopComments.find { it.id == targetId } ?: fail("target $targetId missing from desktop golden")
        val kotlinTarget2 = kotlinComments.find { it.id == targetId } ?: fail("target $targetId missing from Kotlin output")
        assertSameThreadContentAndId(desktopTarget, kotlinTarget2, "resolveB19Sibling target")
        assertTrue(kotlinTarget2.resolved, "the resolved thread should read back resolved")

        // The other FOUR B19 threads (and the ~700 other threads workbook-
        // wide) are byte-for-byte untouched on BOTH sides.
        assertUnrelatedThreadsUntouched(desktopComments, kotlinComments, setOf(targetId), "resolveB19Sibling")
        val b19After = kotlinComments.filter { c -> val s = c.selector; s is CommentSelector.Cell && s.selector.cell == "B19" }
        assertEquals(5, b19After.size, "resolving one B19 thread must not drop or merge its siblings")
    }

    // ── elden-sequence: add (fresh sheet, no prior comment parts) -> reply
    // -> resolve -> reopen -> move CROSS-SHEET (onto a sheet that already
    // has other threads) — the literal "add+reply+resolve+move sequence"
    // design review 1/3 (F11/F2) names, run end to end with the Kotlin
    // writer against the SAME real elden workbook desktop wrote it against. ──
    @Test
    fun eldenSequence() {
        val json = JSONObject(String(xlsxParityResourceBytes("write-golden/elden-sequence.json"), Charsets.UTF_8))
        val fixture = json.getString("fixture")
        val path = json.getString("path")
        val steps = json.getJSONArray("steps")

        val originalBytes = xlsxParityResourceBytes(fixture)
        val kotlinTarget = xlsxParityScratchCopy(originalBytes, fixture)
        val home = xlsxParityScratchHome()

        var currentId: String? = null
        for (i in 0 until steps.length()) {
            val step = steps.getJSONObject(i)
            val op = step.getString("op")
            val args = step.getJSONObject("args")
            when (op) {
                "add" -> {
                    val r = runBlocking {
                        addXlsxComment(kotlinTarget.absolutePath, path, xlsxParitySelector(args.getString("cell"), (if (args.has("sheet")) args.getString("sheet") else null)), args.getString("text"), args.getString("author"), home)
                    }
                    assertTrue(r is XlsxWriteResult.Ok, "eldenSequence step $i (add) failed: $r")
                    currentId = (r as XlsxWriteResult.Ok).value
                }
                "reply" -> {
                    val id = currentId ?: fail("eldenSequence step $i (reply) has no current thread id")
                    val r = runBlocking { replyToXlsxComment(kotlinTarget.absolutePath, path, id, args.getString("text"), args.getString("author"), home) }
                    assertTrue(r is XlsxWriteResult.Ok, "eldenSequence step $i (reply) failed: $r")
                }
                "resolve" -> {
                    val id = currentId ?: fail("eldenSequence step $i (resolve) has no current thread id")
                    val r = runBlocking { resolveXlsxComment(kotlinTarget.absolutePath, path, id, home) }
                    assertTrue(r is XlsxWriteResult.Ok, "eldenSequence step $i (resolve) failed: $r")
                }
                "reopen" -> {
                    val id = currentId ?: fail("eldenSequence step $i (reopen) has no current thread id")
                    val r = runBlocking { reopenXlsxComment(kotlinTarget.absolutePath, path, id, home) }
                    assertTrue(r is XlsxWriteResult.Ok, "eldenSequence step $i (reopen) failed: $r")
                }
                "move" -> {
                    val id = currentId ?: fail("eldenSequence step $i (move) has no current thread id")
                    val r = runBlocking {
                        moveXlsxComment(kotlinTarget.absolutePath, path, id, xlsxParitySelector(args.getString("newCell"), (if (args.has("newSheet")) args.getString("newSheet") else null)), home)
                    }
                    assertTrue(r is XlsxWriteResult.Ok, "eldenSequence step $i (move) failed: $r")
                    currentId = (r as XlsxWriteResult.Ok).value
                }
                else -> fail("eldenSequence: unknown op $op")
            }
        }

        val lastStep = steps.getJSONObject(steps.length() - 1)
        assertEquals("move", lastStep.getString("op"), "eldenSequence's own last step must be the move (this test's own final-state assertions assume it)")
        val moveArgs = lastStep.getJSONObject("args")

        val desktopGolden = xlsxParityScratchCopy(xlsxParityResourceBytes("write-golden/elden-sequence.xlsx"), "desktop-elden-sequence.xlsx")
        val desktopComments = xlsxParityReadOk(desktopGolden, path)
        val kotlinComments = xlsxParityReadOk(kotlinTarget, path)

        val desktopFinal = xlsxParityFindByCell(desktopComments, moveArgs.getString("newCell"), moveArgs.getString("newSheet"))
        val kotlinFinal = xlsxParityFindByCell(kotlinComments, moveArgs.getString("newCell"), moveArgs.getString("newSheet"))
        assertSameThreadContent(desktopFinal, kotlinFinal, "eldenSequence final thread")
        assertEquals(1, kotlinFinal.replies.size, "the reply survives resolve+reopen+move")
        // Sequence order is add -> reply -> resolve -> reopen -> move: reopen
        // is the LAST op that touches `resolved`, and move never changes it,
        // so the final state must be UNRESOLVED.
        assertTrue(!kotlinFinal.resolved, "resolve followed by reopen (then a move, which doesn't touch resolved) must leave the thread unresolved")
        assertTrue(!desktopFinal.resolved, "desktop's own golden output must show the same final unresolved state")

        // The source sheet (`Sorceries & Incantations List`) must have NO
        // thread left at the original cell — the move removed it, it did not
        // duplicate it.
        val stillAtSource = kotlinComments.any { c -> val s = c.selector; s is CommentSelector.Cell && s.selector.cell == "ZZ999" && s.selector.sheet == "Sorceries & Incantations List" }
        assertTrue(!stillAtSource, "the OLD cell must have no thread left after the move")

        // Every one of the ~700 OTHER real threads in this workbook —
        // including the other 4 threads sharing B19 — is untouched.
        assertUnrelatedThreadsUntouched(desktopComments, kotlinComments, setOf(desktopFinal.id, kotlinFinal.id), "eldenSequence")
    }

