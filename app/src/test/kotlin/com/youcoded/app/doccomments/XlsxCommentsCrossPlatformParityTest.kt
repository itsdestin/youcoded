private fun xlsxParityResourceBytes(path: String): ByteArray {
    val stream = object {}.javaClass.getResourceAsStream("/doc-comments/$path") ?: fail("missing test resource doc-comments/$path")
    return stream.use { it.readBytes() }
}

private fun xlsxParityScratchCopy(bytes: ByteArray, name: String): File {
    val dir = Files.createTempDirectory("ycd-xlsx-parity-").toFile()
    dir.deleteOnExit()
    val target = File(dir, name)
    target.writeBytes(bytes)
    return target
}

private fun xlsxParityScratchHome(): File {
    val dir = Files.createTempDirectory("ycd-xlsx-parity-home-").toFile()
    dir.deleteOnExit()
    return dir
}

private fun xlsxParitySelector(cell: String, sheet: String?): CommentSelector = CommentSelector.Cell(CellSelector(cell, sheet))

/** File-private zip introspection for the delete-last-comment-fresh
 *  structural cleanup check — DocxCommentsCrossPlatformParityTest.kt's own
 *  `entryNames`/`entryBytes` are file-private in Kotlin, so this file needs
 *  its own copies rather than sharing them. */
private fun xlsxParityEntryNames(file: File): Set<String> {
    ZipFile(file).use { zip -> return zip.entries().asSequence().filter { !it.isDirectory }.map { it.name }.toSet() }
}

private fun xlsxParityEntryBytes(file: File, name: String): ByteArray? {
    ZipFile(file).use { zip ->
        val entry = zip.getEntry(name) ?: return null
        return zip.getInputStream(entry).use { it.readBytes() }
    }
}

private fun xlsxParityReadOk(file: File, path: String): List<PersistedComment> {
    val r = readXlsxComments(file, path)
    assertTrue(r is XlsxReadResult.Ok, "expected Ok reading $path, got $r")
    return (r as XlsxReadResult.Ok).comments
}

private fun xlsxParityFindByCell(comments: List<PersistedComment>, cell: String, sheet: String? = null): PersistedComment {
    val match = comments.filter { c ->
        val sel = c.selector
        sel is CommentSelector.Cell && sel.selector.cell == cell && (sheet == null || sel.selector.sheet == sheet)
    }
    assertEquals(1, match.size, "expected exactly one thread at $cell${if (sheet != null) "/$sheet" else ""}, found ${match.size}")
    return match[0]
}

/** Field-for-field equality EXCLUDING `id` and `createdAt` — see this file's
 *  own header for why both are expected to differ between two independent
 *  writer runs for a newly-minted or freshly-timestamped thread. */
private fun assertSameThreadContent(expected: PersistedComment, actual: PersistedComment, label: String) {
    assertEquals(expected.selector, actual.selector, "$label: selector")
    assertEquals(expected.text, actual.text, "$label: text")
    assertEquals(expected.author, actual.author, "$label: author")
    assertEquals(expected.resolved, actual.resolved, "$label: resolved")
    assertEquals(expected.replies.size, actual.replies.size, "$label: replies.size")
    for (i in expected.replies.indices) {
        assertEquals(expected.replies[i].author, actual.replies[i].author, "$label: replies[$i].author")
        assertEquals(expected.replies[i].text, actual.replies[i].text, "$label: replies[$i].text")
    }
    assertEquals(expected.history.size, actual.history.size, "$label: history.size")
    for (i in expected.history.indices) {
        assertEquals(expected.history[i].by, actual.history[i].by, "$label: history[$i].by")
        assertEquals(expected.history[i].action, actual.history[i].action, "$label: history[$i].action")
    }
}

/** Same as `assertSameThreadContent`, plus `id` — for a thread this
 *  operation never re-mints (a pre-existing, content-derived GUID). */
private fun assertSameThreadContentAndId(expected: PersistedComment, actual: PersistedComment, label: String) {
    assertEquals(expected.id, actual.id, "$label: id")
    assertSameThreadContent(expected, actual, label)
}

/** Proves every thread OTHER than `excludeIds` is byte-for-byte identical
 *  (including id, excluding createdAt) between Kotlin's own output and
 *  desktop's committed golden output — the direct "an unrelated thread is
 *  never disturbed" guarantee this file's own header explains. */
private fun assertUnrelatedThreadsUntouched(desktopComments: List<PersistedComment>, kotlinComments: List<PersistedComment>, excludeIds: Set<String>, label: String) {
    val desktopRest = desktopComments.filter { it.id !in excludeIds }.sortedBy { it.id }
    val kotlinRest = kotlinComments.filter { it.id !in excludeIds }.sortedBy { it.id }
    assertEquals(desktopRest.size, kotlinRest.size, "$label: unrelated-thread count differs")
    for (i in desktopRest.indices) {
        assertSameThreadContentAndId(desktopRest[i], kotlinRest[i], "$label unrelated[$i]")
    }
}

