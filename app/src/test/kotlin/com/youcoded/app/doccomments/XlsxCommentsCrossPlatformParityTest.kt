// Cross-platform WRITE parity for T21 of the doc-comments build (docs/
// active/specs/2026-09-26-doc-comments-build-design.md §4.3/§4.3a, §8 T21,
// §9.3). Xlsx sibling of `DocxCommentsCrossPlatformParityTest.kt` (see that
// file's own header for the shared rationale) — proves the Kotlin writer and
// the REAL desktop writer (`desktop/src/main/doc-comments/xlsx-comments.ts`)
// agree on the SAME operation(s) against the SAME real-file input, not just
// that each independently passes its own suite.
//
// Fixtures: app/src/test/resources/doc-comments/write-golden/{add-docling,
// move-docling,resolve-b19-sibling,elden-sequence}.{xlsx,json} — the
// desktop writer's OWN real output, generated by the committed script
// `desktop/tests/fixtures/doc-comments/generate-xlsx-write-golden.mjs`
// (copied verbatim into this module's test resources), never hand-
// transcribed.
//
// WHY this does NOT do a docx-style "every untouched PART is byte-identical"
// check: xlsx's own per-sheet threadedComment{N}.xml/comments{N}.xml/
// vmlDrawing{N}.vml numbering is dynamic (assigned by "next available N",
// per shared-fixtures/doc-comments/xlsx-threaded-reference/manifest.json's
// own `partPaths.numberingScheme` note) and a comment on a sheet that
// previously had NONE (this test's own `elden-sequence` case, deliberately
// targeting `Sorceries & Incantations List` — confirmed comment-free in that
// same manifest) creates brand-new parts whose exact names are an
// IMPLEMENTATION DETAIL neither writer's own contract fixes. The guarantee
// this design actually needs — "an unrelated existing thread is never
// disturbed" (§9.3, §4.2's own multi-thread-per-cell risk) — is instead
// proven MORE DIRECTLY and MORE STRONGLY here: reading back the WHOLE
// ~700-thread comment set from both Kotlin's own output and desktop's
// committed golden output and asserting every thread OTHER than the one this
// operation touches is byte-for-byte identical in its OWN read-back shape
// (id, text, author, resolved, replies, history) — a corrupted or dropped
// unrelated part would show up here regardless of which physical XML part it
// lived in.
//
// WHY the touched thread's own `id`/GUID is excluded from the cross-writer
// comparison: `mutateAddXlsxComment` mints a fresh random GUID per call
// (§4.2's `guidFormat`) — two INDEPENDENT writers applied to the same input
// never produce the same GUID for a BRAND-NEW thread, which is expected, not
// drift. A `resolve`/`move` against a PRE-EXISTING thread (`resolve-b19-
// sibling`, `move-docling`) keeps that thread's own real, content-derived
// GUID unchanged, so those two cases DO compare the id for exact equality.
//
// WHY `createdAt` is excluded universally (mirroring the docx parity test's
// own identical exclusion): a `reply`/`add` step stamps real wall-clock time
// (`xlsx-comments.ts`'s `formatThreadedDate(new Date())`) — two independent
// writer runs, run at two different real moments, can never agree on it.
