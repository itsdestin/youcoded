    @Test
    fun readsBothTopLevelCommentsWithTheirAuthorsTextAndResolvedState() {
        val result = readDocxComments(fixtureFile("launch-brief.docx"), "docs/launch-brief.docx")
        assertTrue(result is DocxReadResult.Ok, "expected Ok, got $result")
        val comments = (result as DocxReadResult.Ok).comments
        assertEquals(2, comments.size)

        val goalComment = comments.find { it.text.startsWith("Is 30% realistic") }
        assertTrue(goalComment != null, "expected a comment starting with 'Is 30% realistic'")
        assertEquals("person:Priya Shah", goalComment!!.author)
        assertTrue(goalComment.resolved, "w15:done=\"1\" should read as resolved")
        assertTrue(goalComment.replies.isEmpty())
        assertEquals("docs/launch-brief.docx", goalComment.path)
        val selector = goalComment.selector
        assertTrue(selector is CommentSelector.Text, "expected a text selector")
        assertEquals(
            "Move 30% of weekly active users to the new app within six weeks of launch.",
            (selector as CommentSelector.Text).selector.exact,
        )
    }

    @Test
    fun reconstructsAReplyThreadViaParaIdParent() {
        val result = readDocxComments(fixtureFile("launch-brief.docx"), "docs/launch-brief.docx")
        assertTrue(result is DocxReadResult.Ok, "expected Ok, got $result")
        val comments = (result as DocxReadResult.Ok).comments

        val timelineComment = comments.find { it.text.startsWith("Legal needs the beta terms") }
        assertTrue(timelineComment != null)
        assertTrue(!timelineComment!!.resolved, "w15:done=\"0\" should read as not resolved")
        assertEquals(1, timelineComment.replies.size)
        val reply = timelineComment.replies[0]
        assertEquals("person:Marcus Lee", reply.author)
        assertEquals("Confirmed with legal — the beta terms are ready as of this morning.", reply.text)
        // Account-ready id shape (§1.2): `${commentId}-r${n}`.
        assertEquals("${timelineComment.id}-r1", reply.id)
        // The reply itself is never a separate top-level record.
        assertTrue(comments.none { it.text.contains("Confirmed with legal") })
    }

