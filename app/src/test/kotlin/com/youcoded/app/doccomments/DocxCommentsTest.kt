// Pins T16 of the doc-comments build (docs/active/specs/2026-09-26-doc-
// comments-build-design.md §3.2a, §8): reading Word comments off a REAL
// .docx's comments.xml/commentsExtended.xml parts, in Kotlin, with
// java.util.zip + javax.xml.parsers — no Android framework classes, no
// instrumented/on-device test (a plain `./gradlew test` JVM unit test, per
// T16's own pinning-test row).
//
// Fixtures: app/src/test/resources/doc-comments/{launch-brief,no-comments,
// spanning-comment,deeply-nested,word365-realistic}.docx — the SAME files
// desktop/tests/docx-comments.test.ts reads (copied verbatim from
// desktop/tests/fixtures/doc-comments/), so a fixture drift here can never
// silently make the cross-platform parity claim compare two different
// inputs (the exact risk T16's own design row warns about).
//
// Golden parity: app/src/test/resources/doc-comments/golden/*.json is the
// REAL desktop `readDocxComments` reader's own output for each fixture,
// generated by desktop/tests/fixtures/doc-comments/generate-docx-golden.mjs
// (committed alongside this test — see that script's header for why it runs
// the actual TS reader rather than hand-transcribing expected JSON). Every
// golden-parity test below re-parses the golden JSON and asserts this
// module's own `PersistedComment.toJson()` output is structurally IDENTICAL,
// field for field.
