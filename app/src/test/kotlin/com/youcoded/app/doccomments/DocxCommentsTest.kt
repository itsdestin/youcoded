private fun fixtureFile(name: String): File {
    val resourceStream = object {}.javaClass.getResourceAsStream("/doc-comments/$name")
        ?: fail("missing test resource doc-comments/$name")
    val tmp = Files.createTempFile("ycd-docx-read-", "-$name").toFile()
    tmp.deleteOnExit()
    resourceStream.use { input -> tmp.outputStream().use { output -> input.copyTo(output) } }
    return tmp
}

private fun goldenComments(name: String): JSONArray {
    val stream = object {}.javaClass.getResourceAsStream("/doc-comments/golden/$name")
        ?: fail("missing golden fixture doc-comments/golden/$name")
    val json = stream.use { it.readBytes().toString(Charsets.UTF_8) }
    return JSONObject(json).getJSONArray("comments")
}

/** Deep-equality between two JSON trees (`org.json` gives no `equals()` that
 *  compares by value — `JSONObject.equals` is reference identity). Object
 *  keys are compared as sets before recursing (so a golden file with an
 *  extra/missing field fails loudly rather than passing on a subset match),
 *  arrays are compared in order (field order is never significant, item
 *  order always is — matches how every list in `PersistedComment` — replies,
 *  history, comments — is itself order-significant). */
// `JSONObject.keySet()` was only added to upstream org.json well after
// Android bundled its own fork into `android.jar` (which never got it) — the
// unit-test compile classpath resolves `org.json.JSONObject` against
// whichever jar Gradle orders first, which turned out to be `android.jar`'s
// older API surface (confirmed by an `Unresolved reference 'keySet'` compile
// failure while building this test). `.keys()` (an `Iterator<String>`) is
// the one key-enumeration method present on BOTH android.jar's org.json and
// the real `org.json:json` test dependency, so this helper uses that instead.
private fun keysOf(o: JSONObject): Set<String> {
    val out = mutableSetOf<String>()
    val it = o.keys()
    while (it.hasNext()) out.add(it.next())
    return out
}

private fun assertJsonEquals(expected: Any?, actual: Any?, path: String) {
    when (expected) {
        is JSONObject -> {
            assertTrue(actual is JSONObject, "$path: expected an object, got $actual")
            actual as JSONObject
            val expectedKeys = keysOf(expected)
            assertEquals(expectedKeys, keysOf(actual), "$path: key set differs")
            for (key in expectedKeys) {
                assertJsonEquals(expected.get(key), actual.get(key), "$path.$key")
            }
        }
        is JSONArray -> {
            assertTrue(actual is JSONArray, "$path: expected an array, got $actual")
            actual as JSONArray
            assertEquals(expected.length(), actual.length(), "$path: array length differs")
            for (i in 0 until expected.length()) {
                assertJsonEquals(expected.get(i), actual.get(i), "$path[$i]")
            }
        }
        else -> assertEquals(expected, actual, path)
    }
}

private fun assertMatchesGolden(fixtureBaseName: String, comments: List<PersistedComment>) {
    val expected = goldenComments("$fixtureBaseName.json")
    val actual = JSONArray(comments.map { it.toJson() })
    assertJsonEquals(expected, actual, fixtureBaseName)
}

