    @Test
    fun capturesTheExactQuoteAcrossAParagraphBreakWithCorrectPrefixSuffix() {
        val result = readDocxComments(fixtureFile("spanning-comment.docx"), "docs/spanning-comment.docx")
        assertTrue(result is DocxReadResult.Ok, "expected Ok, got $result")
        val comments = (result as DocxReadResult.Ok).comments
        assertEquals(1, comments.size)
        val c = comments[0]
        assertEquals("Should this be one paragraph instead of two?", c.text)
        val selector = c.selector
        assertTrue(selector is CommentSelector.Text)
        val text = (selector as CommentSelector.Text).selector
        // The exact quote spans the paragraph break: text from two runs in
        // paragraph 1, the paragraph-break newline, then text from two more
        // runs in paragraph 2.
        assertEquals("first half \nsecond half.", text.exact)
        assertTrue(text.prefix.contains("Before the change:"))
        assertTrue(text.suffix.contains("After the note."))
    }

