export interface HeadlessOptions {
  /** Loopback port the app's page connects to. */
  port: number;
  /** This run's sign-in secret, generated by the app and passed in its query string. */
  token: string;
}

/** A window that is already gone: every "send to the main window" fallback in the wiring skips it. */
const NO_WINDOW = { isDestroyed: () => true, webContents: { id: -1, isDestroyed: () => true, send: () => {} } };

function headlessPlatform(): Platform {
  return {
    openExternal: async (url) => { const { shell } = await import('electron'); await shell.openExternal(url); },
    secretStorage: {
      isEncryptionAvailable: () => safeStorage.isEncryptionAvailable(),
      encryptString: (v) => safeStorage.encryptString(v),
      decryptString: (v) => safeStorage.decryptString(v),
    },
    // The sudo helper is a computer feature; a phone has no sudo.
    resolveAskpassPaths: async () => null,
  };
}

export async function bootHeadless(opts: HeadlessOptions): Promise<{ stop: () => Promise<void> }> {
  const userData = app.getPath('userData');
  await fs.promises.mkdir(userData, { recursive: true });
  await rotateLog();
  log('INFO', 'Headless', 'Starting the backend', { version: app.getVersion(), host: hasHost() ? 'app' : 'none', port: opts.port });

  // --- What main.ts builds at module scope ---
  const sessionManager = new SessionManager({ claudeControls: new ClaudeControlBridge(() => path.join(app.getPath('userData'), 'claude-control')) });
  const windowRegistry = new WindowRegistry();
  const pipeName = hookPipeName();
  sessionManager.setPipeName(pipeName);
  const hookRelay = new HookRelay(pipeName);
  // Same repair as main.ts: re-create a deleted hook socket as each session starts.
  sessionManager.on('session-created', () => { void hookRelay.ensureListening(); });
  sessionManager.setReloadPluginsGate((sessionId) => hookRelay.hasPendingPermission(sessionId));
  hookRelay.setSessionGate((sessionId) => sessionManager.hasSession(sessionId));
  const remoteConfig = new RemoteConfig();
  const skillProvider = new LocalSkillProvider();
  skillProvider.ensureMigrated();
  void (async () => {
    await skillProvider.repairPackageVersions();
    void skillProvider.ensureBundledPluginsInstalled();
  })();
  const commandProvider = new CommandProvider(
    () => skillProvider.getInstalled(),
    () => sessionManager.listSessions()[0]?.cwd ?? null,
  );
  skillProvider.setCacheInvalidationListener(() => commandProvider.invalidateCache());

  let nativeRuntime: NativeRuntime | null = null;
  const platform = headlessPlatform();
  const remoteServer = new RemoteServer(sessionManager, hookRelay, remoteConfig, skillProvider, {
    getNativeRuntime: () => nativeRuntime,
    serveBuiltPage: true,
    getFocusSessionId: () => windowRegistry.getFocusSessionId(),
    audience: windowRegistry,
    // No windows: a push meant for "this computer's windows" has nobody to reach.
    broadcastToWindows: () => {},
    local: { port: opts.port, token: opts.token },
  });
  setSyncSpacesWindowBroadcaster(() => {});

  // --- What main.ts does in app.whenReady() before the window ---
  startDailyHeartbeat();
  let firstRunManager: FirstRunManager | undefined;
  try {
    if (FirstRunManager.isFirstRun()) firstRunManager = new FirstRunManager();
  } catch (e) {
    log('ERROR', 'Headless', 'First-run detection failed, skipping', { error: String(e) });
  }

  // Hooks: Claude Code reaches this backend through the relay scripts it is told about in its settings.
  try {
    const { runInstallHooksChore } = require('../launch-settings-chores');
    const r = await runInstallHooksChore({ version: app.getVersion(), packaged: true });
    log('INFO', 'Headless', 'Hooks installed', { copied: r.copied, written: r.written, refused: r.refused });
  } catch (e) {
    log('ERROR', 'Headless', 'Failed to install hooks', { error: String(e) });
  }
  try { await hookRelay.start(); } catch (e) {
    log('ERROR', 'Headless', 'Failed to start hook relay', { error: String(e) });
    // Same fail-closed rule as main.ts: no socket we own means no socket name handed to sessions.
    sessionManager.setPipeName('');
  }
  try {
    const { runSettingsChores } = require('../launch-settings-chores');
    await runSettingsChores();
  } catch (e) {
    log('ERROR', 'Headless', 'Failed to run settings chores', { error: String(e) });
  }
  try {
    const { reconcileMcp } = require('../mcp-reconciler');
    await reconcileMcp();
  } catch (e) {
    log('ERROR', 'Headless', 'Failed to reconcile MCP servers', { error: String(e) });
  }
  try {
    const { startAnnouncementService } = require('../announcement-service');
    startAnnouncementService();
  } catch (e) {
    log('ERROR', 'Headless', 'Failed to start announcement service', { error: String(e) });
  }

  const marketplaceAuthStore = createAuthStore(userData);
  registerMarketplaceApiHandlers(marketplaceAuthStore, skillProvider);
  void reconcileInstalls(marketplaceAuthStore, skillProvider);
  startSocial(marketplaceAuthStore, windowRegistry, remoteServer);
  initArcadeOps(marketplaceAuthStore);
  const welcomeBackStore = createWelcomeBackStore(path.join(userData, 'welcome-back.json'), fs.promises);
  void welcomeBackStore.startup();

  // --- main.ts createWindow(), minus the window ---
  const deviceIdentity = getDeviceIdentity(userData);
  const machineIdentity = getMachineIdentity(userData);
  const holderTakeoverRef: { fn: (sessionId: string, from?: { deviceId: string; device: string }, transferNonce?: string) => void } = { fn: () => {} };
  const leaseDir = path.join(userData, 'Leases');
  const leaseClient = createLeaseClient({
    deviceId: deviceIdentity.id,
    deviceName: os.hostname(),
    leaseDir: () => leaseDir,
    hubRequest: hubLeaseRequest,
    onTakeoverRequest: (sid, from, transferNonce) => holderTakeoverRef.fn(sid, from, transferNonce),
  });
  try { sweepExpiredLeases(leaseDir); } catch { /* best-effort */ }
  const requester = createRequesterTakeover({
    leaseClient,
    syncNow: () => syncSpacesSyncNowAwaited('personal', HANDOFF_SYNC_TIMEOUT_MS),
    materializeOne: (id) => materializeOne(id),
    forceAcquire: (id) => hubLeaseRequest('force-acquire', id, deviceIdentity.id),
    delay: (ms) => new Promise((r) => setTimeout(r, ms)),
  });
  const chatgptEnabled = process.env.YOUCODED_CHATGPT !== '0';
  const chatgptAuth = new ChatGptAuth({
    userDataDir: userData,
    secrets: new SecretsStore(userData, platform.secretStorage),
    appVersion: app.getVersion(),
    openExternal: (url) => platform.openExternal(url),
    pollUsage: chatgptEnabled,
    route: process.env.YOUCODED_CHATGPT_ROUTE === 'official' ? 'official' : 'codex',
  });
  nativeRuntime = createRuntime({ userDataDir: userData, appVersion: app.getVersion(), platform, chatgptAuth, sessionManager });
  const { ipcMain } = await import('electron');
  const ipcWiring = registerIpcHandlers(ipcMain as any, sessionManager, NO_WINDOW as any, skillProvider, commandProvider, hookRelay, remoteConfig, remoteServer, windowRegistry,
    { client: leaseClient, setHolderTakeover: (fn) => { holderTakeoverRef.fn = fn; }, requester, deviceId: deviceIdentity.id, machineId: machineIdentity?.id ?? '' },
    nativeRuntime, welcomeBackStore);

  // First run: the same two paths as main.ts — a fresh install runs the wizard; an existing one checks sign-in lazily.
  if (firstRunManager) {
    const frm = firstRunManager;
    frm.on('state-changed', (state) => remoteServer.broadcast({ type: IPC.FIRST_RUN_STATE, payload: state }));
    bindFirstRunManager({ getManager: () => frm, getState: () => { try { return frm.getState(); } catch { return { currentStep: 'COMPLETE' }; } }, chatgptAuth });
    frm.run().catch((e) => log('ERROR', 'FirstRun', 'Run failed', { error: String(e) }));
  } else {
    let late: FirstRunManager | null = null;
    let check: Promise<any> | null = null;
    const getState = () => {
      if (late) { try { return late.getState(); } catch { return { currentStep: 'COMPLETE' }; } }
      check ??= (async () => {
        try {
          const { detectAuth } = require('../prerequisite-installer');
          if (await setupIsUsable({ isSignedIn: () => chatgptAuth.isSignedIn(), hasUsableProvider: ipcWiring.hasUsableProvider, detectAuth })) return { currentStep: 'COMPLETE' };
          markSetupCompleted();
          late = new FirstRunManager();
          late.forceStep('AUTHENTICATE');
          late.on('state-changed', (state) => remoteServer.broadcast({ type: IPC.FIRST_RUN_STATE, payload: state }));
          return late.getState();
        } catch {
          return { currentStep: 'COMPLETE' };
        }
      })();
      return check;
    };
    bindFirstRunManager({ getManager: () => late, getState, chatgptAuth: chatgptEnabled ? chatgptAuth : null });
  }

  // Permission asks: the same auto-approve rules as the computer, then every screen that watches the session.
  const docCommentsServerIds = new Map<string, string>();
  sessionManager.on('doc-comments-mcp-attached', (sessionId: string, _cwd: string, _token: string, serverId: string) => { docCommentsServerIds.set(sessionId, serverId); });
  sessionManager.on('session-exit', (sessionId: string) => { docCommentsServerIds.delete(sessionId); });
  trackOutsideComments(sessionManager, hookRelay); // card #207, same as main.ts
  hookRelay.on('hook-event', (event) => {
    if (event.type === 'PermissionRequest') {
      const toolName = event.payload?.tool_name as string;
      const toolInput = event.payload?.tool_input as Record<string, unknown> | undefined;
      const requestId = event.payload?._requestId as string;
      const mode = event.payload?.permission_mode as string | undefined;
      const commentAsk = judgeCommentAsk(event); // card #207 — see main.ts
      if (requestId && commentAsk !== 'ask' && (commentAsk === 'approve' || shouldAutoApproveDocComment(toolName, toolInput, mode, docCommentsServerIds.get(event.sessionId)) || shouldAutoApprove(toolName, toolInput, getPermissionOverrides()))) {
        hookRelay.respond(requestId, { decision: { behavior: 'allow' } });
      }
    }
    ipcWiring.publish(event.sessionId, IPC.HOOK_EVENT, event, { windows: () => {} });
  });
  hookRelay.on('permission-expired', (sessionId: string, requestId: string, reason?: string) => {
    const evt = { type: 'PermissionExpired', sessionId, payload: { _requestId: requestId, _reason: reason }, timestamp: Date.now() };
    ipcWiring.publish(sessionId, IPC.HOOK_EVENT, evt, { windows: () => {} });
  });

  // --- main.ts's post-window services ---
  const syncService = new SyncService();
  setSyncService(syncService);
  syncService.start().catch((e) => log('ERROR', 'Headless', 'SyncService start failed', { error: String(e) }));
  setGithubClient(createGithubClient({ storageDir: userData, safeStorage, log: (m) => log('INFO', 'GithubClient', m) }));
  setSyncSpacesRemoteBroadcaster((e) => remoteServer.broadcast({ type: 'syncspaces:event', payload: e }));
  setSyncSpacesAuthStore(marketplaceAuthStore);
  setSyncSpacesLeaseEventListener((ev) => {
    if (ev.kind === 'takeover-request' || ev.kind === 'taken') leaseClient.handleTakeoverRequest(ev.sessionId, ev.from, ev.transferNonce, ev.senderDeviceId);
  });
  startSyncSpaces(async () => loadSpaceBackupTargets(getSyncConfig), (m) => log('INFO', 'SyncSpaces', m), machineIdentity?.id ?? null)
    .catch((e) => log('ERROR', 'Headless', 'SyncSpaces start failed', { error: String(e) }));
  try {
    const pr = getManagedRoots()?.personalRoot;
    if (pr && machineIdentity) void upsertSelf(pr, { id: machineIdentity.id, platform: process.platform }).catch(() => {});
    if (pr) sweepLegacyLeaseDir(pr);
  } catch { /* sync not configured */ }
  void startConversationStore({ pauseSweeps: true })
    .then(() => runSlugRepair())
    .catch((e) => log('ERROR', 'Headless', 'ConversationStore start / slug repair failed', { error: String(e) }))
    .finally(() => resumeSweeps());
  startTagRegistry();
  startChatsearchIndex();
  startOutboxDrain(ipcWiring.outboxBroadcast);

  // Last: open the door. The app waits for this line before it loads its page.
  await remoteServer.start();
  log('INFO', 'Headless', 'Ready', { port: opts.port });
  console.log(`YOUCODED_HEADLESS_READY ${opts.port}`);

  return {
    stop: async () => {
      remoteServer.stop();
      void ipcWiring.cleanup?.();
      await nativeRuntime?.cleanup();
      void sessionManager.destroyAll?.();
    },
  };
}
