// headless-boot.ts — the desktop backend with no windows: what the Android app runs.
//
// WHY (2026-10-14, Android clean rebuild P1): the phone runs the computer's own backend instead of a
// Kotlin copy of it. This file is main.ts's backend half — the same objects, built in the same order,
// wired to the same channel table — minus everything that draws (windows, buddy, tray, Office, the
// built-in browser, desktop voice). The only screen is the Android app's WebView, which signs in to
// the socket door in local mode (remote-server.ts) as this backend's owner.
//
// Keep it in step with main.ts: a service main.ts starts that a phone should also have belongs here
// too. Loaded only through headless-main.ts, after `electron` points at electron-headless.ts.
