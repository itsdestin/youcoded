#!/usr/bin/env node
// Refreshes src/shared/bundled-plugin-pins.ts: the exact wecoded-marketplace commit each
// built-in (bundled) plugin is installed from. Run this as part of every app release.
//
//   node scripts/refresh-bundled-plugin-pins.mjs           # rewrite the pins file
//   node scripts/refresh-bundled-plugin-pins.mjs --check   # exit 1 if the file is stale/missing
//   --repo <path-or-url>   marketplace to read (default: the public GitHub repo, branch master)
//   --branch <name>        branch to pin to (default: master)
//
// WHY (2026-10 security audit, item 24): built-in plugins used to update themselves at every
// launch to whatever was newest on GitHub, with no fingerprint check. The app now only installs
// the commit written here, so a plugin changes on a user's machine only when the app updates.
//
// A plugin's pin is the LAST commit that touched its folder (not the branch tip), so a pin only
// moves when that plugin really changed. --check fails when a folder has a newer commit than
// its pin, which is what stops a release shipping stale pins; desktop-release.yml runs it.
//
// The pure helpers are exported for tests/refresh-bundled-plugin-pins.test.ts; the git work is
// behind main() so importing this file never touches the network.
import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(HERE, '..', 'src', 'shared', 'bundled-plugin-pins.ts');
const IDS_FILE = path.join(HERE, '..', 'src', 'shared', 'bundled-plugins.ts');
const DEFAULT_REPO = 'https://github.com/itsdestin/wecoded-marketplace.git';

/** The bundled ids, read from the one list the app uses so the two can never drift. */
export function parseBundledIds(source) {
  const block = source.match(/BUNDLED_PLUGIN_IDS\s*=\s*\[([\s\S]*?)\]\s*as const/);
  if (!block) throw new Error('could not find BUNDLED_PLUGIN_IDS in bundled-plugins.ts');
  // Strip // comments first so a quoted word inside a comment is not read as an id.
  const noComments = block[1].replace(/\/\/.*$/gm, '');
  return [...noComments.matchAll(/'([A-Za-z0-9_-]+)'/g)].map((m) => m[1]);
}

/** Renders the generated TypeScript file. Stable output so --check can compare text. */
export function renderPinsFile(pins) {
  const rows = Object.keys(pins).sort().map((id) => {
    const p = pins[id];
    return `  '${id}': { commit: '${p.commit}', sourceRef: '${p.sourceRef}', version: '${p.version}' },`;
  });
  return `// GENERATED by desktop/scripts/refresh-bundled-plugin-pins.mjs. Do not edit by hand.
// Run \`node scripts/refresh-bundled-plugin-pins.mjs\` at every app release (docs/build-and-release.md).
//
// WHY (2026-10 security audit, item 24): each built-in plugin is installed from this exact
// wecoded-marketplace commit and no other, so a plugin only changes when the app updates.
// \`commit\` is a full 40-character git commit id; \`version\` is the plugin.json version at that
// commit (used only to decide whether a user already has something newer).

export interface BundledPluginPin {
  /** Full commit id in itsdestin/wecoded-marketplace that this app release installs. */
  commit: string;
  /** Folder of the plugin inside that repository. */
  sourceRef: string;
  /** plugin.json version at that commit. */
  version: string;
}

export const BUNDLED_PLUGIN_PINS: Record<string, BundledPluginPin> = {
${rows.join('\n')}
};
`;
}

function git(repo, ...args) {
  return execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).trim();
}

/** plugin.json version of `id` at `commit`, trying both layouts the app reads. */
export function versionAt(repo, commit, folder) {
  for (const rel of ['plugin.json', '.claude-plugin/plugin.json']) {
    try {
      const v = JSON.parse(git(repo, 'show', `${commit}:${folder}/${rel}`)).version;
      if (typeof v === 'string' && v) return v;
    } catch { /* try the next layout */ }
  }
  throw new Error(`${folder} has no plugin.json version at ${commit}`);
}

/** Computes the pins from a marketplace checkout (needs history + trees for `ref`). */
export function computePins(repo, ref, ids) {
  const pins = {};
  for (const id of ids) {
    const commit = git(repo, 'log', '-1', '--format=%H', ref, '--', id);
    if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error(`no commit found for plugin folder "${id}" on ${ref}`);
    pins[id] = { commit, sourceRef: id, version: versionAt(repo, commit, id) };
  }
  return pins;
}

function main() {
  const args = process.argv.slice(2);
  const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
  const check = args.includes('--check');
  const repoArg = opt('--repo', DEFAULT_REPO);
  const branch = opt('--branch', 'master');
  const ids = parseBundledIds(fs.readFileSync(IDS_FILE, 'utf8'));

  let repo = repoArg;
  let tmp = null;
  let ref = `origin/${branch}`;
  if (/^https?:\/\//.test(repoArg)) {
    // Blobless bare clone: full commit + folder history (needed for "last commit that touched
    // this folder") without downloading every file.
    tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'yc-pins-'));
    execFileSync('git', ['clone', '--bare', '--filter=blob:none', '--branch', branch, repoArg, tmp], { stdio: 'inherit' });
    repo = tmp;
    ref = branch;
  } else {
    // A local checkout: refresh its remote view so "newest" really is the newest.
    try { git(repo, 'fetch', 'origin', branch); } catch { /* offline: use what is there */ }
  }
  try {
    const pins = computePins(repo, ref, ids);
    const next = renderPinsFile(pins);
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : '';
    if (check) {
      if (current !== next) {
        console.error('Built-in plugin pins are stale or missing. Run: node scripts/refresh-bundled-plugin-pins.mjs');
        process.exit(1);
      }
      console.log(`Built-in plugin pins are current (${ids.length} plugins).`);
      return;
    }
    fs.writeFileSync(OUT_FILE, next);
    for (const id of ids) console.log(`${id}  ${pins[id].version}  ${pins[id].commit}`);
    console.log(current === next ? 'No change.' : `Wrote ${path.relative(process.cwd(), OUT_FILE)}. Commit it with the release.`);
  } finally {
    if (tmp) fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
